CREATE TABLE `usage_record` (
  `id` bigint NOT NULL AUTO_INCREMENT,
  `occurred_at` datetime NOT NULL,
  `provider` varchar(32) NOT NULL,
  `model` varchar(128) NOT NULL,
  `auth_index` varchar(64) NOT NULL,
  `account` varchar(190) NOT NULL,
  `session_id` varchar(64) NOT NULL,
  `client_key` varchar(8) NOT NULL,
  `endpoint` varchar(64) NOT NULL,
  `input_tokens` int NOT NULL,
  `output_tokens` int NOT NULL,
  `reasoning_tokens` int NOT NULL,
  `cache_read_tokens` int NOT NULL,
  `cache_creation_tokens` int NOT NULL,
  `total_tokens` int NOT NULL,
  `latency_ms` int NOT NULL,
  `failed` tinyint NOT NULL,
  `status_code` int NOT NULL,
  `request_tail` varchar(8) NOT NULL DEFAULT '',
  `cache_creation5m_tokens` int NOT NULL DEFAULT '0',
  `cache_creation1h_tokens` int NOT NULL DEFAULT '0',
  `record_key` varchar(40) DEFAULT NULL,
  `request_id` varchar(64) NOT NULL DEFAULT '',
  `ttft_ms` int NOT NULL DEFAULT '0',
  `user_agent` varchar(190) NOT NULL DEFAULT '',
  `reasoning_effort` varchar(32) NOT NULL DEFAULT '',
  `parent_session_id` varchar(64) NOT NULL DEFAULT '',
  `node_kind` varchar(32) NOT NULL DEFAULT '',
  `is_compaction` tinyint NOT NULL DEFAULT '0',
  `raw` json DEFAULT NULL,
  `is_retry` tinyint NOT NULL DEFAULT '0',
  `superseded` tinyint NOT NULL DEFAULT '0',
  `occurred_micros` int NOT NULL DEFAULT '0',
  PRIMARY KEY (`id`),
  UNIQUE KEY `usage_record_key` (`record_key`),
  KEY `usage_occurred` (`occurred_at`),
  KEY `usage_account` (`auth_index`,`occurred_at`),
  KEY `usage_session` (`session_id`),
  KEY `usage_request` (`request_tail`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
